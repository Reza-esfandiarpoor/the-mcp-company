    down_path = (
        Path(__file__)
        .parents[4]
        .joinpath('data/webdav_download.sh')
        .resolve()
        .absolute()
        .as_posix()
    )
    currid = uuid4().hex
    Path(f'/tmp/{currid}').mkdir(exist_ok=True, parents=True)
    # fmt: off
    subprocess.run(['openssl', 'enc', '-aes-256-cbc', '-salt', '-in', down_path, '-out', f'/tmp/{currid}/d', '-pass', 'pass:onetwo3cakes'], check=True)
    subprocess.run(['openssl', 'enc', '-aes-256-cbc', '-salt', '-in', up_path, '-out', f'/tmp/{currid}/u', '-pass', 'pass:onetwo3cakes'], check=True)
    subprocess.run(['docker', 'cp', f'/tmp/{currid}/d', f'{runtime.container.short_id}:/d'], check=True)
    subprocess.run(['docker', 'cp', f'/tmp/{currid}/u', f'{runtime.container.short_id}:/u'], check=True)
    ##################################
    ## Copy new task file
    ##################################
    _base_task_name = task_short_name.removesuffix('-image')
    if os.getenv('TAGC_TASK_PARDIR') is not None:
        src_path = (
            Path(os.getenv('TAGC_TASK_PARDIR'))
            .joinpath(_base_task_name + '.md')
            .resolve()
            .absolute()
            .as_posix()
        )
        dst_path = f'{runtime.container.short_id}:/instruction/task.md'
        subprocess.run(['docker', 'cp', src_path, dst_path], check=True)
    ##################################
    ## Copy New Eval Script
    ##################################
    if os.getenv('TAGC_EVAL_PARDIR') is not None:
        src_path = (
            Path(os.getenv('TAGC_EVAL_PARDIR'))
            .joinpath(_base_task_name + '.py')
            .resolve()
            .absolute()
            .as_posix()
        )
        _tmp_path = f'/tmp/{uuid4().hex}'
        _enc_cmd = [sys.executable, Path(__file__).parents[4].joinpath('data/encrypt.py'), '-i', src_path, '-o', _tmp_path]
