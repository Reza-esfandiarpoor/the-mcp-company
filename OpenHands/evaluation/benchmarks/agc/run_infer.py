def get_config(
    base_container_image: str,
    task_short_name: str,
    mount_path_on_host: str,
    llm_config: LLMConfig,
    agent_config: AgentConfig | None,
    mcp_config: dict | None,
) -> OpenHandsConfig:
    sandbox_config = get_default_sandbox_config_for_eval()
    sandbox_config.base_container_image = base_container_image
    sandbox_config.enable_auto_lint = True
    # If the web services are running on the host machine, this must be set to True
    sandbox_config.use_host_network = True
    config_kwargs = {}
    if mcp_config is not None:
        config_kwargs['mcp'] = mcp_config
    config = OpenHandsConfig(
        run_as_openhands=False,
        max_budget_per_task=4,
        max_iterations=100,
        save_trajectory_path=os.path.join(
            mount_path_on_host, f'traj_{task_short_name}.json'
        ),
        sandbox=sandbox_config,
        # we mount trajectories path so that trajectories, generated by OpenHands
        # controller, can be accessible to the evaluator file in the runtime container
        workspace_mount_path=mount_path_on_host,
        workspace_mount_path_in_sandbox='/outputs',
        **config_kwargs,
    )
    config.set_llm_config(llm_config)
    if agent_config:
        config.set_agent_config(agent_config)
    else:
        logger.info('Agent config not provided, using default settings')
        agent_config = AgentConfig(
            enable_prompt_extensions=False,
        )
        config.set_agent_config(agent_config)
    return config


def load_dependencies(runtime: Runtime) -> list[str]:
    """
    Every task has a dependencies.yml file, which lists all the services that the
    task depends on. This function loads the file and returns all dependent service names.
    """
    command = 'cat /utils/dependencies.yml'
    action = CmdRunAction(command=command)
    logger.info(action, extra={'msg_type': 'ACTION'})
    obs: CmdOutputObservation = runtime.run_action(action)
    logger.info(obs, extra={'msg_type': 'OBSERVATION'})
    assert obs.exit_code == 0
    dependencies = yaml.safe_load(obs.content)
    if dependencies is None:
        dependencies = []
    return dependencies


def init_task_env(runtime: Runtime, hostname: str, env_llm_config: LLMConfig):
    command = (
        f"echo >> /etc/hosts && "
        f"sed -i 's|bash /utils/reset.sh|bash /utils/reset.sh \&\& python_default /wait_for_service_in_init.py|' /utils/init.sh && "
        f"sed -i 's|python_default /npc/run_multi_npc.py|sleep 5 \&\& python_default /npc/run_multi_npc.py|' /utils/init.sh && "
        f'SERVER_HOSTNAME={hostname} '
        f'LITELLM_API_KEY={env_llm_config.api_key.get_secret_value() if env_llm_config.api_key else None} '
        f'LITELLM_BASE_URL={env_llm_config.base_url} '
        f'LITELLM_MODEL={env_llm_config.model} '
        'bash /utils/init.sh'
    )
    action = CmdRunAction(command=command)
    action.set_hard_timeout(900)
    logger.info(action, extra={'msg_type': 'ACTION'})
    obs = runtime.run_action(action)
    logger.info(obs, extra={'msg_type': 'OBSERVATION'})
    assert obs.exit_code == 0


def codeact_user_response(state: State) -> str:
    msg = (
        'Please continue working on the task on whatever approach you think is suitable.\n'
        'If you think you have solved the task, please finish the interaction.\n'
        'IMPORTANT: YOU SHOULD NEVER ASK FOR HUMAN HELP.\n'
    )

    if state.history:
        # check if the agent has tried to talk to the user 3 times, if so, let the agent know it can give up
        user_msgs = [
            event
            for event in state.history
            if isinstance(event, MessageAction) and event.source == 'user'
        ]
        if len(user_msgs) >= 2:
            # let the agent know that it can give up when it has tried 3 times
            return (
                msg
                + 'If you want to give up, run: <execute_bash> exit </execute_bash>.\n'
            )
    return msg


def run_solver(
    runtime: Runtime,
    task_name: str,
    config: OpenHandsConfig,
    dependencies: list[str],
    save_final_state: bool,
    state_dir: str,
    save_screenshots: bool,
    screenshots_dir: str,
) -> State:
    instruction = 'Complete the task in /instruction/task.md'

    if 'gitlab' in dependencies:
        instruction += "\n\nGitlab username is 'root' and password is 'theagentcompany'"

    state: State | None = asyncio.run(
        run_controller(
            config=config,
            sid=task_name,
            initial_user_action=MessageAction(content=instruction),
            runtime=runtime,
            fake_user_response_fn=codeact_user_response,
        )
    )
    logger.info(state)

    if save_screenshots:
        screenshots_dir = os.path.join(screenshots_dir, task_name)
        ##################################
        ## Make sure screenshots are not overwritten if the experiment is being run again
        ## It is bad because in each folder, there are multiple images and if all of them are not overwritten,
        ## then we don't know which ones are valid
        ##################################
        scd=Path(screenshots_dir)
        if scd.exists():
            scd.rename(scd.parent.joinpath(scd.name + '_' + uuid4().hex))
        ##################################
        os.makedirs(screenshots_dir, exist_ok=True)
        for image_id, obs in enumerate(state.history):
            if isinstance(obs, BrowserOutputObservation):
                image_data = base64.b64decode(
                    obs.screenshot.replace('data:image/png;base64,', '')
                )
                with open(
                    os.path.join(screenshots_dir, f'{image_id}.png'), 'wb'
                ) as file:
                    file.write(image_data)
                if obs.set_of_marks:
                    som_image_data = base64.b64decode(
                        obs.set_of_marks.replace('data:image/png;base64,', '')
                    )
                    with open(
                        os.path.join(screenshots_dir, f'{image_id}_som.png'), 'wb'
                    ) as file:
                        file.write(som_image_data)

    if save_final_state:
        os.makedirs(state_dir, exist_ok=True)
        with open(os.path.join(state_dir, f'state_{task_name}.json'), 'w') as file:
            json.dump(str(state), file)

    return state


def run_evaluator(
    runtime: Runtime, env_llm_config: LLMConfig, trajectory_path: str, result_path: str
):
    #####################################
    ## If the tmux window is messed up because of using 'cat' on a binary file,
    ## clean it up first and then run evals
    #####################################
    ec_obs = runtime.run_action(CmdRunAction(command='echo'))
    if ec_obs.exit_code == -1:
        ec_obs = runtime.run_action(CmdRunAction(command='C-l', is_input=True))
    #####################################
    ec_obs = runtime.run_action(CmdRunAction(command='echo'))
    if ec_obs.exit_code != 0 or os.environ.get('USE_DOCKER_FOR_EVAL', 'false').lower() == 'true':
        cmd = [
            "docker", "exec",
            "-w", "/workspace",
            "-e", f"LITELLM_API_KEY={env_llm_config.api_key.get_secret_value() if env_llm_config.api_key else None}",
            "-e", f"LITELLM_BASE_URL={env_llm_config.base_url}",
            "-e", f"LITELLM_MODEL={env_llm_config.model}",
            "-e", "DECRYPTION_KEY=theagentcompany is all you need",
            runtime.container.short_id,
            "python_default", "/utils/eval.py", "--trajectory_path", f"{trajectory_path}", "--result_path", f"{result_path}",
        ]
        eval_timeout = 600
        if os.environ.get('DOCKER_EVAL_NO_TIMEOUT', 'false').lower() == 'true':
            eval_timeout = None
        obs = subprocess.run(cmd, check=False, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=eval_timeout)
        std_cnt = '========================== START EVAL OUTPUT FROM DIRECT DOCKER RUN ==========================\n'
        std_cnt += obs.stdout
        std_cnt += '\n========================== END EVAL OUTPUT FROM DIRECT DOCKER RUN =========================='
        print(std_cnt)
        assert obs.returncode == 0
        return std_cnt
    else:
        command = (
            f'LITELLM_API_KEY={env_llm_config.api_key.get_secret_value() if env_llm_config.api_key else None} '
            f'LITELLM_BASE_URL={env_llm_config.base_url} '
            f'LITELLM_MODEL={env_llm_config.model} '
            f"DECRYPTION_KEY='theagentcompany is all you need' "  # Hardcoded Key
            f'python_default /utils/eval.py --trajectory_path {trajectory_path} --result_path {result_path}'
        )
        action = CmdRunAction(command=command)
        action.set_hard_timeout(600)
        logger.info(action, extra={'msg_type': 'ACTION'})
        obs = runtime.run_action(action)
        logger.info(obs, extra={'msg_type': 'OBSERVATION'})
        assert obs.exit_code == 0
        return obs.content


def run_cmd_in_runtime(
    runtime: Runtime, command: str, echo_output: bool = True
) -> None:
    action = CmdRunAction(command=command)
    action.set_hard_timeout(600)
    logger.info(action, extra={'msg_type': 'ACTION'})
    obs = runtime.run_action(action)
    logger.info(obs, extra={'msg_type': 'OBSERVATION'})
    assert obs.exit_code == 0
    if echo_output:
        pprint(obs)
    return obs.content


